"""Markdown report of the AI-rater stand-in for the summary hand check (issue #34).

Reads the AI-rated sheets `summary_audit_ai_rater_<n>_<dataset>.csv` (same rows and columns as the blank
`summary_audit_sheet_<dataset>.csv`, filled by one blinded rater each) and the keys made by
`make_audit_sheet.py --write-key` (not in the repo), and writes

- per rater and dataset, the agreement of its labels with the automatic flags (the table of `audit_agreement.py`);
- per dataset, the agreement between the two raters, per property;
- per rater and dataset, how many summaries of each method it marked (counts of 10; the key unblinds the methods).

    python scripts/audit_ai_report.py --sheets-dir docs/results --key-dir results/audit_keys \\
        --out docs/results/summary_audit_ai_raters.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from kslimeans.summary_audit import HAND_LABELS, agreement_markdown, compare_raters, compare_with_key, method_rates

DATASETS = ("clinc150_intent", "bank77")
RATERS = (1, 2)
PAIR_HEADER = ["property", "n", "rater 1 yes", "rater 2 yes", "both", "rater 1 only", "rater 2 only", "neither",
               "raw agreement", "kappa"]  # fmt: skip


def rates_markdown(rates: pd.DataFrame, suffix: str = "") -> str:
    """Counts per method and property: the hand labels as `marked/rated` (`suffix` ""), or the automatic flags."""
    names = [p.replace("_", " ") for p in HAND_LABELS]
    lines = ["| method | " + " | ".join(names) + " |", "| --- | " + " | ".join(["---:"] * len(names)) + " |"]
    for r in rates.to_dict("records"):
        cells = [f"{r[p + suffix]}" if suffix else f"{r[p]}/{r[p + '_rated']}" for p in HAND_LABELS]
        lines.append(f"| {r['method']} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def report(sheets_dir: Path, key_dir: Path) -> str:
    out = ["# AI-rater stand-in for the summary hand check (issue #34)", "",
           "Generated by `scripts/audit_ai_report.py`. These are ratings by two AI instances, not a human rating; "
           "see `summary_quality.md` section 5 for what they do and do not support. Properties are the hand labels "
           "of `docs/summary_audit_rubric.md`; \"auto\" is the automatic flag of the same name. Kappa is 0 when "
           "only one of the two labellings ever marks a summary and `nan` when neither does."]  # fmt: skip
    for dataset in DATASETS:
        key = pd.read_csv(key_dir / f"summary_audit_key_{dataset}.csv")
        sheets = {n: pd.read_csv(sheets_dir / f"summary_audit_ai_rater_{n}_{dataset}.csv") for n in RATERS}
        out += ["", f"## {dataset}"]
        for n, sheet in sheets.items():
            table = agreement_markdown(compare_with_key(sheet, key))
            out += ["", f"### Rater {n} against the automatic flags", "", table]
        pair = compare_raters(sheets[1], sheets[2])
        out += ["", "### Rater 1 against rater 2", "", agreement_markdown(pair, PAIR_HEADER)]
        for n, sheet in sheets.items():
            out += ["", f"### Rater {n}: summaries marked per method (marked/rated)", "",
                    rates_markdown(method_rates(sheet, key))]  # fmt: skip
        out += ["", "### Automatic flags on the same summaries (flagged, of 10 per method)", "",
                rates_markdown(method_rates(sheets[1], key), "_auto")]  # fmt: skip
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sheets-dir", required=True)
    parser.add_argument("--key-dir", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    Path(args.out).write_text(report(Path(args.sheets_dir), Path(args.key_dir)))


if __name__ == "__main__":
    main()
